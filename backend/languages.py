# Also accept full English names (case-insensitive) from older UI values.
_NAME_TO_CODE = {name.lower(): code for code, name in WHISPER_LANGUAGES.items()}

DEFAULT_LANGUAGE = "en"


def normalize_language(language: str) -> str:
    value = (language or "").strip().lower()
    if value in WHISPER_LANGUAGES:
        return value
    if value in _NAME_TO_CODE:
        return _NAME_TO_CODE[value]
    raise ValueError(f"Unsupported language: {language}")


def languages_for_api() -> list[dict[str, str]]:
    items = [
        {"code": code, "label": label}
        for code, label in WHISPER_LANGUAGES.items()
    ]
    items.sort(key=lambda item: (0 if item["code"] == DEFAULT_LANGUAGE else 1, item["label"]))
    return items
